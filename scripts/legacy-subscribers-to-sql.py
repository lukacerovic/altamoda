#!/usr/bin/env python3
"""
Build a Postgres import of the old altamoda.rs newsletter audience.

    python3 -I scripts/legacy-subscribers-to-sql.py <altamoda_db.sql> <out_dir>

Only addresses that opted in on the old site are included:
  - every row of the old `newsletter_subscribers` table, and
  - registered users with users.notify_email = 1 ("obaveštavaj me e-mailom").
Registered users who never opted in are NOT added.

Segment: b2b when the address belongs to an old user with vp_prices=1 (salon
with wholesale prices), otherwise b2c. Blocked users, guests and invalid/test
addresses are skipped.

Writes (personal data: keep under /backups/, never commit):
  <out_dir>/legacy-subscribers-import.sql   run with psql against the target DB
  <out_dir>/legacy-subscribers-report.csv   every address + decision

The import is idempotent: an address that already exists in
newsletter_subscribers is left alone (so someone who unsubscribed on the new
site stays unsubscribed). Imported ids start with 'legacy_ns_'; roll back with
  DELETE FROM newsletter_subscribers WHERE id LIKE 'legacy\\_ns\\_%';
"""
import csv
import hashlib
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from legacy_dump import load  # noqa: E402

EMAIL_RE = re.compile(r'^[^\s@,;]+@[^\s@,;]+\.[a-z]{2,}$')
SKIP_EMAIL_DOMAINS = {
    'mailinator.com', 'mailinator.net', 'example.com', 'test.com', 'pera.com',
    'yopmail.com', 'guerrillamail.com', 'tempmail.com',
}


def q(v):
    return "'" + v.replace("'", "''") + "'"


def main():
    dump, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    d = load(dump, ['newsletter_subscribers', 'users'])

    users = {}
    for u in d['users']:
        e = (u['email'] or '').strip().lower()
        if e:
            users[e] = u

    sources = {}  # email -> (source, date)
    for s in d['newsletter_subscribers']:
        e = (s['email'] or '').strip().lower()
        if e:
            sources.setdefault(e, ('newsletter', s['date']))
    for e, u in users.items():
        if u['notify_email'] == '1' and e not in sources:
            sources[e] = ('user notify_email', u['date_registered'])

    rows, report = [], []
    for e, (src, when) in sorted(sources.items()):
        u = users.get(e)
        reason = None
        if not EMAIL_RE.match(e):
            reason = 'invalid email'
        elif e.split('@', 1)[1] in SKIP_EMAIL_DOMAINS:
            reason = 'test/fake domain'
        elif u and u['blocked_user'] == '1':
            reason = 'blocked user'
        segment = 'b2b' if u and u['vp_prices'] == '1' else 'b2c'
        report.append([e, src, segment, reason or 'import'])
        if reason:
            continue
        when = when if when and not when.startswith('0000') else None
        rows.append((e, segment, when))

    sql = [
        '-- Old-site newsletter audience (opt-in only). Generated by scripts/legacy-subscribers-to-sql.py',
        'BEGIN;',
    ]
    for e, segment, when in rows:
        sid = 'legacy_ns_' + hashlib.sha1(e.encode()).hexdigest()[:20]
        ts = q(when) + '::timestamp' if when else 'now()'
        sql.append(
            'INSERT INTO newsletter_subscribers (id, email, segment, is_subscribed, subscribed_at) '
            f"SELECT {q(sid)}, {q(e)}, {q(segment)}::\"NewsletterSegment\", true, {ts} "
            f'WHERE NOT EXISTS (SELECT 1 FROM newsletter_subscribers WHERE lower(email) = {q(e)});'
        )
    sql.append('COMMIT;')
    with open(os.path.join(out_dir, 'legacy-subscribers-import.sql'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(sql) + '\n')
    with open(os.path.join(out_dir, 'legacy-subscribers-report.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['email', 'source', 'segment', 'decision'])
        w.writerows(report)

    b2b = sum(1 for r in rows if r[1] == 'b2b')
    print(f'opt-in addresses: {len(sources)}  import: {len(rows)} (b2b {b2b}, b2c {len(rows) - b2b})  '
          f'skipped: {len(sources) - len(rows)}')


if __name__ == '__main__':
    main()
